"""提示词。

System Prompt 里每一段都有明确目的,不是随便堆的:

  * 能力边界 —— 先告诉模型「你看不见文件」,它才不会凭空编造代码内容;
  * 工具说明 —— 四个工具什么时候该用哪个,写清楚才能提高选择准确率;
  * 工作纪律 —— 先读后评、先静态后语义、行号必须来自工具,这几条是抑制幻觉的主力;
  * 输出格式 —— 固定模板,终端渲染才好看,报告之间也能横向比较;
  * 等级判据 —— 不写清楚的话,模型会把所有问题都标成 HIGH;
  * 语言 —— 必须覆盖到中间话术,不只管最终报告。
"""

from __future__ import annotations


# ----------------------------------------------------------------------
